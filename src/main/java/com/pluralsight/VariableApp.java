package com.pluralsight;

public class VariableApp {
    public static void main(String[] args) {
//Part 1
        String favoriteColor;
        System.out.println("My answer is: String favoriteColor;");

        int javaFocusStartYear;
        System.out.println("My answer is: int javaFocusStartYear;");

        char middleInitial;
        System.out.println("My answer is: char middleInitial;");

        boolean havePets;
        System.out.println("My answer is: boolean havePets;");

        String haveANiceDay;
        System.out.println("My answer is: String haveANiceDay;");
//Part 2
        int numberDaysInWeek = 7;
        System.out.println("The number of days in a week is " + numberDaysInWeek + ".");

        double priceOfCoffee = 4.99;
        System.out.println("The price of coffee is $" + priceOfCoffee + ".");

        char favoriteLetter = 'J';
        System.out.println("My favorite letter is " + favoriteLetter + ".");

        boolean isItRaining = true;
        System.out.println("Is it raining? " + isItRaining);
    }
}
